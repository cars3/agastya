#!/usr/bin/env python3
"""bench_searchtome.py -- compare Jev + EmbeddingGemma against the published
STAIR / SearchTome baselines on the public 6-domain release.

Rows produced per domain (gold = dataset's own test queries, not generated by us):
  - BM25 (local, same-data control)          R@1 / R@3 / nDCG@3
  - Gemma-only dense retriever                R@1 / R@3 / nDCG@3
  - Jev leaf decision (flat noul top-3)       R@1 / R@3 / nDCG@3
  - Jev + Gemma product (Jev filters, Gemma ranks the filtered set;
                            Gemma top3 added, top5 fallback)
                                              R@1 / R@3 / nDCG@3 + set-hit

Published reference (paper, 18 books, not a reproduction target):
  STAIR 82.6 | DSI 76.9 | DPR 68.7 | BM25 59.5 | raw Mistral 13.8  (R@1)

Jev calls are cached per (domain, query_id) in data/searchtome/jevalks_<domain>.json
so reruns never pay for the same query twice. Default samples --limit queries per
domain; --full runs every test query (about 6k Jev calls).

    .venv/bin/python bench_searchtome.py --limit 120
    .venv/bin/python bench_searchtome.py --full --workers 6
"""

import argparse
import json
import math
import os
import random
import re
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import numpy as np
from datasets import load_dataset
from rank_bm25 import BM25Okapi
from typesafe_sdk import Noul

from gemma import embed_documents, embed_query, load_model, top_k
from jev import ask

DOMAINS = ["education", "finance", "law", "medicine", "natural_sciences", "social_sciences"]
PUBLISHED = {"STAIR": 82.6, "DSI": 76.9, "DPR": 68.7, "BM25": 59.5, "Mistral": 13.8}
DOC_CHAR_LIMIT = 8000
CACHE_DIR = Path(__file__).resolve().parent / "data" / "searchtome"
JEV_JOIN = 0.85          # relative cutoff, same as core.py's walk
GEMMA_TOP_K = 3          # embedding leaves added after the Jev decision
EMBED_FALLBACK_K = 5     # embedding leaves when the Jev decision keeps nothing


def metrics_from_ranks(ranks: list[int]) -> dict:
    arr = np.asarray(ranks)
    if arr.size == 0:
        return {"R@1": 0.0, "R@3": 0.0, "nDCG@3": 0.0}
    return {
        "R@1": float(np.mean(arr < 1)),
        "R@3": float(np.mean(arr < 3)),
        "nDCG@3": float(np.mean([1 / math.log2(r + 2) if r < 3 else 0.0 for r in arr])),
    }


def rank_of(gold: str, ordered_titles: list[str]) -> int:
    try:
        return ordered_titles.index(gold)
    except ValueError:
        return len(ordered_titles) + 1000


def jev_flat_scores(question: str, titles: list[str]) -> list[float]:
    """One Jev call: a noul per section title (the flat leaf decision)."""
    response = ask(
        state=(
            f"Question: {question}\n"
            f"Candidate sections: " + "; ".join(titles)
        ),
        questions={
            f"s{i}": Noul(
                instructions=f"Does the section '{title}' likely contain the answer to the question?"
            )
            for i, title in enumerate(titles)
        },
    )
    return [response.nouls[f"s{i}"].noul for i in range(len(titles))]


def walk_jev(question: str, titles: list[str], retries: int = 2) -> list[float]:
    for attempt in range(retries + 1):
        try:
            return jev_flat_scores(question, titles)
        except Exception as exc:  # noqa: BLE001
            if attempt == retries:
                print(f"  ! jev failed: {type(exc).__name__}: {exc}")
                return [0.0] * len(titles)
            time.sleep(1.5 * (attempt + 1))
    return [0.0] * len(titles)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=120, help="sampled test queries per domain")
    ap.add_argument("--full", action="store_true", help="run every test query")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--domains", default=",".join(DOMAINS))
    args = ap.parse_args()

    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    model = load_model()
    rng = random.Random(args.seed)

    table = {}
    for domain in [d.strip() for d in args.domains.split(",") if d.strip()]:
        print(f"\n=== {domain} ===", flush=True)
        corpus = load_dataset("meghanadh/SearchTome", f"{domain}_corpus", split="corpus")
        tests = load_dataset("meghanadh/SearchTome", f"{domain}_queries", split="test")
        titles = [row["title"] for row in corpus]
        contents = [row["content"] or "" for row in corpus]
        title_set = set(titles)

        idxs = list(range(len(tests)))
        if not args.full and args.limit < len(idxs):
            idxs = sorted(rng.sample(idxs, args.limit))
        qs = [(tests[i]["query_id"], tests[i]["query"], tests[i]["gold_doc_title"]) for i in idxs]
        qs = [q for q in qs if q[2] in title_set]
        print(f"sections: {len(titles)} | test queries: {len(tests)} | sampled: {len(qs)}", flush=True)

        # ---- embed corpus + queries
        doc_texts = [f"{t}\n{c[:DOC_CHAR_LIMIT]}" for t, c in zip(titles, contents)]
        doc_vecs = embed_documents(model, doc_texts, batch_size=4)
        q_vecs = np.vstack([
            embed_query(model, q[1]) for q in qs
        ]) if qs else np.zeros((0, doc_vecs.shape[1]), dtype=np.float32)

        # ---- BM25
        tokenized = [f"{t} {c[:DOC_CHAR_LIMIT]}".lower().split() for t, c in zip(titles, contents)]
        bm25 = BM25Okapi(tokenized)
        bm25_ranks = []
        for _, query, gold in qs:
            scores = bm25.get_scores(query.lower().split())
            order = [titles[i] for i in np.argsort(-scores)]
            bm25_ranks.append(rank_of(gold, order))

        # ---- Gemma-only dense
        gemma_ranks = []
        for qi, (_, query, gold) in enumerate(qs):
            order = [titles[int(i)] for i in np.argsort(-(doc_vecs @ q_vecs[qi]))]
            gemma_ranks.append(rank_of(gold, order))

        # ---- Jev flat scores (cached)
        cache_path = CACHE_DIR / f"jevalks_{domain}.json"
        cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}
        missing = [q for q in qs if str(q[0]) not in cache]
        if missing:
            print(f"jev: {len(missing)} uncached queries, {args.workers} workers", flush=True)
            t0 = time.time()
            with ThreadPoolExecutor(max_workers=args.workers) as pool:
                futs = {pool.submit(walk_jev, q[1], titles): q for q in missing}
                for done, fut in enumerate(as_completed(futs), 1):
                    qid = futs[fut][0]
                    cache[str(qid)] = fut.result()
                    if done % 25 == 0 or done == len(futs):
                        print(f"  jev {done}/{len(futs)} ({time.time()-t0:.0f}s)", flush=True)
            cache_path.write_text(json.dumps(cache))

        jev_ranks, union_ranks, union_sets, set_hits = [], [], [], []
        for qi, (qid, query, gold) in enumerate(qs):
            nouls = np.asarray(cache[str(qid)])
            jev_order = [titles[i] for i in np.argsort(-nouls)]
            jev_ranks.append(rank_of(gold, jev_order))

            gemma_order = [titles[int(i)] for i in np.argsort(-(doc_vecs @ q_vecs[qi]))]

            # Product semantics: Jev filters (every section within 15% of the
            # best noul, the flat analogue of the walk cutoff), Gemma ranks the
            # filtered set, Gemma top-3 added as extra candidates, Gemma top-5
            # as fallback when Jev keeps nothing.
            best = float(nouls.max()) if nouls.size else 0.0
            walked = [titles[i] for i in np.argsort(-nouls)
                      if best > 0 and nouls[i] >= JEV_JOIN * best]
            product_set: list[str] = list(walked)
            if product_set:
                for t in gemma_order[:GEMMA_TOP_K]:
                    if t not in product_set:
                        product_set.append(t)
            else:
                product_set = list(gemma_order[:EMBED_FALLBACK_K])

            sims_all = doc_vecs @ q_vecs[qi]
            sim_of = {titles[i]: float(sims_all[i]) for i in range(len(titles))}
            ordered = sorted(product_set, key=sim_of.get, reverse=True)
            union_ranks.append(rank_of(gold, ordered))
            union_sets.append(len(product_set))
            set_hits.append(gold in product_set)

        table[domain] = {
            "sections": len(titles),
            "queries": len(qs),
            "bm25": metrics_from_ranks(bm25_ranks),
            "gemma": metrics_from_ranks(gemma_ranks),
            "jev": metrics_from_ranks(jev_ranks),
            "jev_gemma": {**metrics_from_ranks(union_ranks),
                          "set_hit": float(np.mean(set_hits)),
                          "avg_set": float(np.mean(union_sets))},
        }
        for name, row in table[domain].items():
            if isinstance(row, dict) and "R@1" in row:
                print(f"  {name:10s} R@1={row['R@1']:.3f}  R@3={row['R@3']:.3f}  nDCG@3={row['nDCG@3']:.3f}",
                      flush=True)

    print("\n=== macro average over domains ===")
    systems = ["bm25", "gemma", "jev", "jev_gemma"]
    for name in systems:
        r1 = np.mean([table[d][name]["R@1"] for d in table])
        r3 = np.mean([table[d][name]["R@3"] for d in table])
        nd = np.mean([table[d][name]["nDCG@3"] for d in table])
        print(f"  {name:10s} R@1={r1:.3f}  R@3={r3:.3f}  nDCG@3={nd:.3f}")
    print("  published  " + "  ".join(f"{k}={v}" for k, v in PUBLISHED.items()) + "  (R@1, paper setup)")

    out = CACHE_DIR / ("results_full.json" if args.full else f"results_limit{args.limit}.json")
    out.write_text(json.dumps({"published": PUBLISHED, "domains": table}, indent=2))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
